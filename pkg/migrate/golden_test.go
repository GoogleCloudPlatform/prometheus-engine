// testGoldenEquivalence executes inputs through the full Migrator / CLI pipeline,
// compiles the resulting GMP outputs with ScrapeConfigs(), and asserts 0-diff against raw upstream .golden files.
func testGoldenEquivalence(t *testing.T, goldenFileName string, inputs []runtime.Object, endpointPort string) {
	t.Helper()

	var (
		sdRole           = promk8s.RolePod
		primaryNamespace string
		primaryName      string
		svcLabels        map[string]string
	)

	var yamlBuf bytes.Buffer
	for _, in := range inputs {
		switch obj := in.(type) {
		case *pomonitoringv1.PodMonitor:
			sdRole = promk8s.RolePod
			primaryNamespace = obj.Namespace
			primaryName = obj.Name
			if obj.Kind == "" {
				obj.Kind = "PodMonitor"
				obj.APIVersion = "monitoring.coreos.com/v1"
			}
		case *pomonitoringv1.ServiceMonitor:
			sdRole = promk8s.RoleEndpoint
			primaryNamespace = obj.Namespace
			primaryName = obj.Name
			if obj.Kind == "" {
				obj.Kind = "ServiceMonitor"
				obj.APIVersion = "monitoring.coreos.com/v1"
			}
		case *corev1.Service:
			if obj.Kind == "" {
				obj.Kind = "Service"
				obj.APIVersion = "v1"
			}
			svcLabels = obj.Labels
		}

		data, err := k8syaml.Marshal(in)
		if err != nil {
			t.Fatalf("marshal input object error: %v", err)
		}
		if _, err := yamlBuf.WriteString("---\n"); err != nil {
			t.Fatalf("write YAML separator error: %v", err)
		}
		if _, err := yamlBuf.Write(data); err != nil {
			t.Fatalf("write YAML data error: %v", err)
		}
	}

	migrator := NewMigrator()
	migrator.RegisterConverter(&PodMonitorConverter{})
	migrator.RegisterConverter(&ServiceMonitorConverter{})
	migrator.Stdin = &yamlBuf
	migrator.Stderr = io.Discard

	report, err := migrator.Run("-")
	if err != nil {
		t.Fatalf("migrator.Run failed: %v", err)
	}
	if len(report.Outputs) == 0 {
		t.Fatal("no outputs produced by migrator")
	}

	// Iterate across all output resources and collect all compiled ScrapeConfigs.
	var allGMPScrapeCfgs []*config.ScrapeConfig
	for _, output := range report.Outputs {
		if output == nil {
			continue
		}
		switch output.GetKind() {
		case "PodMonitoring":
			var gmpPM monitoringv1.PodMonitoring
			if err := runtime.DefaultUnstructuredConverter.FromUnstructured(output.Object, &gmpPM); err != nil {
				t.Fatalf("FromUnstructured PodMonitoring error: %v", err)
			}
			// TODO: Inject mock Secret pool references into ScrapeConfigs() if future upstream test cases test
			// basicAuth, bearerToken, or TLS secret references against golden files.
			cfgs, err := gmpPM.ScrapeConfigs("test_project", "test_location", "test_cluster", nil)
			if err != nil {
				t.Fatalf("ScrapeConfigs error: %v", err)
			}
			allGMPScrapeCfgs = append(allGMPScrapeCfgs, cfgs...)
		case "ClusterPodMonitoring":
			var gmpCPM monitoringv1.ClusterPodMonitoring
			if err := runtime.DefaultUnstructuredConverter.FromUnstructured(output.Object, &gmpCPM); err != nil {
				t.Fatalf("FromUnstructured ClusterPodMonitoring error: %v", err)
			}
			cfgs, err := gmpCPM.ScrapeConfigs("test_project", "test_location", "test_cluster", nil)
			if err != nil {
				t.Fatalf("ScrapeConfigs error: %v", err)
			}
			allGMPScrapeCfgs = append(allGMPScrapeCfgs, cfgs...)
		}
	}

	goldenPath := filepath.Join("testdata", "golden", goldenFileName)
	goldenData, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("cannot read golden file %s: %v", goldenPath, err)
	}
	var poPromCfg config.Config
	if err := yaml.Unmarshal(goldenData, &poPromCfg); err != nil {
		t.Fatalf("unmarshaling golden file: %v", err)
	}
	if len(poPromCfg.ScrapeConfigs) == 0 {
		t.Fatalf("no scrape configs found in %s", goldenFileName)
	}

	if len(allGMPScrapeCfgs) != len(poPromCfg.ScrapeConfigs) {
		// TODO: If future upstream test cases evaluate multi-namespace namespaceSelector fixtures against golden files,
		// add multi-ScrapeConfig aggregation to reconcile GMP's split PodMonitoring CRDs against PO's single ScrapeConfig.
		t.Fatalf("scrape config count mismatch: got %d, want %d", len(allGMPScrapeCfgs), len(poPromCfg.ScrapeConfigs))
	}

	for i, expectedPO := range poPromCfg.ScrapeConfigs {
		normalizedGMP := normalizeGMPScrapeConfig(allGMPScrapeCfgs[i], expectedPO, sdRole, primaryNamespace, primaryName, endpointPort, svcLabels)

		poYAML, err := yaml.Marshal(expectedPO)
		if err != nil {
			t.Fatalf("marshal PO YAML error: %v", err)
		}
		gmpYAML, err := yaml.Marshal(normalizedGMP)
		if err != nil {
			t.Fatalf("marshal GMP YAML error: %v", err)
		}

		if diff := cmp.Diff(string(poYAML), string(gmpYAML)); diff != "" {
			t.Errorf("normalized GMP scrape config [%d] mismatch with raw PO golden (-PO, +GMP):\n%s", i, diff)
		}
	}
}

